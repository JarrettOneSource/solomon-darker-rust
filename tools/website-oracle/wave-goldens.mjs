#!/usr/bin/env node
// Retains the complete authored wave table as typed Rust data and records the native compiler.
import { writeFileSync, mkdirSync } from 'node:fs'
import { resolve } from 'node:path'
import { loadKernel, root, writeFixture } from './oracle.mjs'
import { rustEnemy as enemy, rustFlag as flag } from './rust-enemy-data.mjs'

const { NATIVE_RETAIL_WAVES } = await loadKernel('core-kernels/native-retail-wave-schedule.ts')
const timeline = await loadKernel('core-kernels/boneyard-wave-timeline.ts')
const native = await loadKernel('core-kernels/native-rng.ts')

const rows = NATIVE_RETAIL_WAVES.map(wave => `    WaveDef {
        spawn: ${wave.spawn}, spawn_delay: [${wave.spawnDelay}], wave_delay: [${wave.waveDelay}],
        max_enemies: ${wave.maxEnemies}, zombie_wave: ${wave.zombieWave === true}, next: &[${wave.next}],
        groups: &[${wave.groups.map(group => `WaveGroup { entries: &[${group.entries.map(entry =>
          `WaveGroupEntry { enemy: ${enemy(entry.enemy)}, flags: &[${entry.flags.map(flag).join(', ')}] }`).join(', ')}] }`).join(', ')}],
    }`).join(',\n')
const output = resolve(root, 'crates/sim/src/boneyard/waves/retail_schedule.rs')
mkdirSync(resolve(root, 'crates/sim/src/boneyard/waves'), { recursive: true })
writeFileSync(output, `//! Generated by tools/website-oracle/wave-goldens.mjs from the complete pinned
//! Website core-kernels/native-retail-wave-schedule.ts. Preserve row and GROUP order.

use crate::enemies::{EnemyFlag, EnemyToken};
use super::{WaveDef, WaveGroup, WaveGroupEntry};

pub const RETAIL_WAVES: &[WaveDef] = &[\n${rows}\n];\n`)

const cases = []
for (const seed of ['0', '1', '7', '12345678', 'ffffffff']) {
  let rng = native.createNativeRng(timeline.seedBoneyardWaveRng(`${seed}:wave-compiler`))
  const opening = timeline.compileBoneyardOpening(rng)
  rng = opening.rngState
  const sections = []
  for (let index = 0; index < NATIVE_RETAIL_WAVES.length; index++) {
    const compiled = timeline.compileBoneyardWaveSection(NATIVE_RETAIL_WAVES[index], index + 1, rng)
    sections.push(compiled)
    rng = compiled.rngState
  }
  cases.push({ seed, opening, sections })
}
writeFixture('wave-compiler-goldens.json', 'tools/website-oracle/wave-goldens.mjs',
  'Website/frontend/src/game/core-kernels/boneyard-wave-timeline.ts and native-retail-wave-schedule.ts',
  { cases })
console.log(`retained ${NATIVE_RETAIL_WAVES.length} wave rows, ${NATIVE_RETAIL_WAVES.reduce((count, wave) => count + wave.groups.length, 0)} GROUPs`)
