// Public cast-pose/emitter kernels and authored weapon anchors, without editing the Website.
import { writeFileSync } from 'node:fs'
import { resolve } from 'node:path'
import { loadKernel, point, root, writeFixture } from './oracle.mjs'
const spells = await loadKernel('core-kernels/primary-spells.ts')
const weapon = await loadKernel('core-kernels/native-player-weapon.ts')
const character = await loadKernel('core-kernels/player-character.ts')
const regions = await loadKernel('core-kernels/hub-regions.ts')
const number = value => Number.isInteger(value) ? `${value}.0` : String(value)
const vector = value => `Vec2::new(${number(value.x)}, ${number(value.y)})`
const bank = (count, offset) => Array.from({ length: count }, (_, pose) =>
  `    [\n        // Native pose ${pose}.\n${Array.from({ length: 24 }, (_, heading) => `        ${vector(offset(heading, pose))},`).join('\n')}\n    ],`).join('\n')
const data = `//! Authored attachment anchors generated by tools/website-oracle/primary-cast-goldens.mjs.\n//! Source: core-kernels/native-player-weapon.ts and player-weapon-attachment-program.json.\nuse crate::Vec2;\n\npub const STAFF_OFFSETS: [[Vec2; 24]; 10] = [\n${bank(10, weapon.playerStaffAttachmentOffset)}\n];\npub const WAND_OFFSETS: [[Vec2; 24]; 3] = [\n${bank(3, weapon.playerWandSpellEmitterOffset)}\n];\npub const BARE_OFFSETS: [Vec2; 24] = [\n${Array.from({ length: 24 }, (_, heading) => `    ${vector(weapon.playerHandSpellEmitterOffset(heading))},`).join('\n')}\n];\n`
writeFileSync(resolve(root, 'crates/sim/src/spells/weapon_offsets.rs'), data)
const poses = []
for (const element of ['air', 'earth', 'ether', 'fire', 'water']) {
  for (const actionTick of [-1, 0, 1, 13.333333, 14, 17.777779, 18, 27, 36, 55, 73]) {
    for (const channelActive of [false, true]) {
      poses.push([element, actionTick, channelActive, spells.primaryCastPose(actionTick, channelActive, element)])
    }
  }
}
const emitters = []
for (let heading = 0; heading < 24; heading += 1) {
  for (const [kind, element, ticks] of [
    ['staff', 'fire', [0, 1, 18, 36]], ['wand', 'ether', [0, 1]], [null, 'ether', [0]],
  ]) {
    for (const tick of ticks) {
      emitters.push([heading, kind, element, tick, point(spells.primarySpellEmitterOffset(heading, tick, false, element, kind))])
    }
  }
}
const aims = []
for (const [position, aim, scale] of [
  [{ x: 100, y: 100 }, { x: 300, y: 50 }, 1.2],
  [{ x: 0, y: 0 }, { x: 0, y: -25 }, 1],
  [{ x: -10, y: 5 }, { x: -150, y: 90 }, 0.7],
]) aims.push([point(position), point(aim), scale, point(spells.primarySpellAimDirection(position, aim, scale))])
const player = character.createPlayerCharacter({ element: 'ether', discipline: 'arcane', displayName: 'Facing oracle' }, { x: 100, y: 100 })
player.headingIndex = 0
player.primaryCast.actionTick = 0
const walk = character.planPlayerCharacterTick(player, { movement: { x: 1, y: 0 } }, 1)
const scripted = regions.planHubScriptedMovement(player, { x: 200, y: 100 }, 1)
const facings = [walk, scripted].map(plan => character.commitPlayerCharacterTick(player, plan, { x: player.position.x + plan.delta.x, y: player.position.y + plan.delta.y }).headingIndex)
writeFixture('primary-cast-goldens.json', 'tools/website-oracle/primary-cast-goldens.mjs',
  'Website/frontend/src/game/core-kernels: primary-spells.ts, native-player-weapon.ts, player-character.ts, hub-regions.ts', { poses, emitters, aims, facings })
