#!/usr/bin/env node
// Executes the unmodified current field kernels; every floating value retains its raw bits.
import { execFileSync } from 'node:child_process'
import { writeFileSync } from 'node:fs'
import { resolve } from 'node:path'
import { loadKernel, root, websiteDir, writeFixture } from './oracle.mjs'
const drain = await loadKernel('core-kernels/native-ether-drain.ts')
const random = await loadKernel('core-kernels/native-rng.ts')
const { NATIVE_TREE_OCCLUSION_POLYGONS } = await loadKernel('core-kernels/native-tree-geometry.ts')
const rustFloat = value => Number.isInteger(value) ? `${value}.0` : String(value)
const polygons = NATIVE_TREE_OCCLUSION_POLYGONS.map(polygon => `    &[${polygon.map(point => `Vec2::new(${rustFloat(point.x)}, ${rustFloat(point.y)})`).join(', ')}]`).join(',\n')
writeFileSync(resolve(root,'crates/sim/src/secondary/ether_drain/trees.rs'), `//! Retained native-tree-geometry.ts polygons; generated by current-ether-drain-goldens.mjs.\nuse crate::Vec2;\npub(super) const TREE_POLYGONS: &[&[Vec2]] = &[\n${polygons}\n];\n`)
const sourceRevision = execFileSync('git', ['rev-parse', 'HEAD'], { cwd: websiteDir, encoding: 'utf8' }).trim()
const bits = value => {
  if (typeof value === 'number') {
    const buffer = Buffer.alloc(8); buffer.writeDoubleBE(value)
    return `f64:${buffer.toString('hex')}`
  }
  if (Array.isArray(value)) return value.map(bits)
  if (value && typeof value === 'object') return Object.fromEntries(Object.entries(value).map(([key,value]) => [key,bits(value)]))
  return value
}
const snake = value => {
  if (Array.isArray(value)) return value.map(snake)
  if (value && typeof value === 'object') return Object.fromEntries(Object.entries(value).map(([key,value]) => [key.replace(/[A-Z]/g,letter=>`_${letter.toLowerCase()}`),snake(value)]))
  return value
}
const field = {alpha:Math.fround(.7),damage:3750,id:51,ownerId:'owner',position:{x:250.125,y:-300.25}}
const contacts=[]
for(const distance of [0,9.999,10,14.999,15,19.999,20,120.125,511.999,512,512.001]) {
  for(const [flags,forceFactor,activationDelayTicks] of [[2,1,0],[0x801,1,0],[2,.35,0],[2,Math.fround(.1),0],[0x400,1,0],[0x400,1,1]]) {
    const target={activationDelayTicks,forceFactor,nativeFlags:flags,position:{x:field.position.x+distance,y:field.position.y},
      ref:flags&0x400?{kind:'loot',id:3,registrationOrdinal:8}:flags&1?{kind:'player',id:'peer'}:{kind:'enemy',id:2,registrationOrdinal:4}}
    const contact=drain.nativeEtherDrainContact(field,target)
    contacts.push({field,target,result:contact?bits(snake({...contact,hitStrength:0})):null})
  }
}
const animationContacts=[]
for(const distance of [0,9.999,10,100,512,1023,1200]) for(const bounceVelocity of [0,1,-1]) {
  const target={bounceVelocity,position:{x:field.position.x+distance,y:field.position.y-3},ref:{kind:'golem-fragment',id:2,index:3}}
  animationContacts.push({field,target,result:bits(snake(drain.nativeEtherDrainWorldAnimationContact(field,target)))})
}
const references=[]
let state=null
const center={x:0,y:0}
const target=(kind,id,ordinal,x,y,flags=kind==='loot'?0x400:2)=>({activationDelayTicks:0,forceFactor:1,nativeFlags:flags,position:{x,y},
  ref:kind==='loot'||kind==='enemy'?{kind,id,registrationOrdinal:ordinal}:{kind,id}})
const membershipSteps=[
  {refresh:false,targets:[target('enemy',1,1,0,0),target('loot',1,2,2000,0),target('player','owner',0,10,10,0x801),target('golem',7,0,20,20,0x800)]},
  {refresh:false,targets:[target('enemy',1,1,2000,0),target('loot',1,2,2000,0),target('player','owner',0,2000,0,0x801),target('golem',7,0,20,20,0x800)]},
  {refresh:false,targets:[target('enemy',1,9,10,0),target('loot',1,2,2000,0),target('loot',2,10,0,840),target('player','owner',0,2000,0,0x801)]},
  {refresh:false,targets:[target('enemy',1,9,10,0),target('loot',2,10,0,840),target('loot',3,11,0,900)]},
  {refresh:true,targets:[target('enemy',1,9,10,0),target('loot',3,11,0,900),target('enemy',2,12,0,819.2),target('enemy',3,13,0,819.199)]},
  {refresh:false,targets:[]},
]
for(const input of membershipSteps) {
  const source=state
  const result=drain.refreshNativeEtherDrainTargets(source,input.targets,center,input.refresh)
  state=result.state
  references.push({source,center,...input,result:bits(snake(result))})
}
const worldReferences=[]
state=drain.createNativeEtherDrainState()
const animationTarget=(kind,id,x,index=0)=>({bounceVelocity:0,position:{x,y:0},ref:kind==='golem-fragment'?{kind,id,index}:{kind,id}})
const worldSteps=[
  {initialized:false,targets:[animationTarget('golem-fragment',2,10,0),animationTarget('golem-fragment',2,20,1),animationTarget('death-weapon',1,30),animationTarget('enemy-death-effect',1,1024)]},
  {initialized:true,targets:[animationTarget('golem-fragment',2,2000,0),animationTarget('golem-fragment',2,20,1),animationTarget('death-weapon',1,30),animationTarget('enemy-death-effect',1,20)]},
  {initialized:true,targets:[animationTarget('golem-fragment',3,10,0),animationTarget('golem-fragment',3,20,1),animationTarget('death-weapon',2,30),animationTarget('primary-transient',9,40),animationTarget('secondary-actor',7,30)]},
  {initialized:true,targets:[]},
]
for(const input of worldSteps) {
  const source=state
  state=drain.refreshNativeEtherDrainWorldAnimations(source,input.targets,center,input.initialized)
  worldReferences.push({source,center,...input,result:bits(snake(state))})
}
const debris=[]
for(const position of [{x:0,y:0},{x:1,y:0},{x:33.125,y:-19.5},{x:750.25,y:123.75}]) {
  const animation=drain.createNativeEtherDrainDebris(center,position,97.25,13.125,2)
  debris.push({center,position,result:bits(snake(animation))})
}
const animationSteps=[]
for(const seed of [1,17,91]) {
  let rng=random.createNativeRng(seed)
  let animations=[...debris.map(row=>drain.createNativeEtherDrainDebris(center,row.position,97.25,13.125,2)),
    {kind:'captured',alpha:Math.fround(1.25-Math.fround(.2)),atlas:'Demon',entry:80,tint:0xffffff,bodyYOffset:0}]
  const frames=[]
  for(let tick=0;tick<240;tick++) {
    const result=drain.stepNativeEtherDrainAnimations(animations,center,rng)
    frames.push({tick,result:bits(snake(result))}); rng=result.rng;animations=result.animations
    if(animations.length===0)break
  }
  animationSteps.push({seed,frames})
}
const leaves=[...NATIVE_TREE_OCCLUSION_POLYGONS,
  [{x:0,y:0},{x:3,y:0},{x:3,y:6},{x:0,y:6}],
  [{x:-41.125,y:17.25},{x:87.5,y:19.75},{x:100.125,y:130.5},{x:-90,y:171.25}],
]
writeFixture('current-ether-drain-goldens.json','tools/website-oracle/current-ether-drain-goldens.mjs','core-kernels/native-ether-drain.ts',
  {sourceRevision,contacts,animationContacts,references,worldReferences,debris,animationSteps,
    leaves:leaves.map(polygon=>({polygon,result:bits(drain.nativeEtherDrainLeafCenter(polygon))})),
    families:['SKELETON','SKELETONARCHER','SKELETONMAGE','ZOMBIE','DEMON','SPIDER','IMP','WRAITH','MAGGOT','DIREFACULTY','DEMONSKULL','HEARTMONGER','COFFIN','COCOON','PORTAL'].map(family=>({family,
      force:bits(drain.nativeEtherDrainEnemyForceFactor(family)),captures:drain.nativeEtherDrainCapturesFamily(family)}))})
