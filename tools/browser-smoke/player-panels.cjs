// Real native model commands through the Rust Inventory and Skillbook surfaces.
const assert = require('node:assert/strict');
const path = require('node:path');
const { chromium } = require(path.resolve(process.env.PW));
const { startNewGame } = require('./menu-journey.cjs');
const output = process.env.OUT || '/tmp';
const url = process.env.URL || 'http://127.0.0.1:4185/';
const state = page => page.evaluate(() => Array.from(window.wasmBindings.wizard_state()));
const shot = (page, name) => page.screenshot({ path: path.join(output, name) });
const panel = (page, name) => page.locator(`.player-panels:not([hidden]) [data-player-panel="${name}"]`).waitFor();
const frames = page => page.evaluate(() => new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve))));

(async () => {
  const browser = await chromium.launch({ headless: true,
    executablePath: process.env.CHROME || '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome',
    args: ['--use-angle=swiftshader', '--enable-unsafe-swiftshader', '--ignore-gpu-blocklist'] });
  const errors = [];
  try {
    const page = await browser.newPage({ viewport: { width: 1600, height: 900 } });
    page.on('pageerror', error => errors.push(error.message));
    page.on('console', message => { if (message.type() === 'error') errors.push(message.text()); });
    page.on('response', response => { if (response.status() >= 400) errors.push(`${response.status()} ${response.url()}`); });
    await page.goto(url);
    await page.waitForFunction(() => window.wasmBindings?.wizard_state().length > 0 && !document.getElementById('status').textContent, null, { timeout: 60000 });
    await startNewGame(page, {name:'Felix'});
    await page.keyboard.press('KeyI');
    await panel(page,'inventory');
    await page.waitForTimeout(450);
    const frozen = await state(page);
    await page.keyboard.down('KeyS'); await frames(page); await page.keyboard.up('KeyS');
    assert.deepEqual(await state(page),frozen,'the inventory owns movement and freezes local simulation');
    await shot(page,'inventory-rust.png');
    const health = page.getByRole('button',{name:'Health Potion, quantity 1',exact:true});
    await health.click();
    await page.waitForTimeout(250);
    await page.locator('.player-panel-tooltip').getByText('Restores your health to maximum',{exact:false}).waitFor();
    await shot(page,'inventory-rust-potion.png');
    await health.dblclick();
    await health.waitFor({state:'detached'});
    const mana = page.getByRole('button',{name:'Mana Potion, quantity 1',exact:true});
    const source = await mana.boundingBox();
    const destination = await page.locator('[data-panel-action="cell:5"]').boundingBox();
    await page.mouse.move(source.x+source.width/2,source.y+source.height/2);
    await page.mouse.down(); await frames(page);
    await page.mouse.move(destination.x+destination.width/2,destination.y+destination.height/2,{steps:12});
    await page.mouse.up();
    await page.waitForFunction(() => document.querySelector('[aria-label="Mana Potion, quantity 1"]')?.dataset.inventorySlot === '5');
    const hat = page.locator('[data-panel-action="equipment:hat"]');
    await hat.dblclick();
    await page.getByRole('heading',{name:'A WIZARD WOULD NEVER REMOVE HIS HAT!'}).waitFor();
    await page.locator('[data-panel-action="notice-okay"]').click();
    await page.getByRole('heading',{name:'A WIZARD WOULD NEVER REMOVE HIS HAT!'}).waitFor({state:'detached'});
    const weapon = page.locator('[data-panel-action="equipment:weapon"]').first();
    await weapon.dblclick();
    await page.waitForFunction(() => document.querySelector('[data-panel-action="equipment:weapon"]').getAttribute('aria-label').endsWith('empty'));
    const staff = page.getByRole('button',{name:'Staff, quantity 1',exact:true});
    await staff.dblclick();
    await page.waitForFunction(() => !document.querySelector('[data-panel-action="equipment:weapon"]').getAttribute('aria-label').endsWith('empty'));
    await weapon.dblclick();
    await staff.waitFor();
    await staff.click();
    await page.locator('[data-panel-action="unforge"]').click();
    await page.getByRole('heading',{name:'REALLY UNFORGE THIS?'}).waitFor();
    await shot(page,'inventory-rust-unforge-confirm.png');
    await page.locator('[data-panel-action="unforge-cancel"]').click();
    await staff.waitFor();
    await page.locator('[data-panel-action="unforge"]').click();
    await page.locator('[data-panel-action="unforge-confirm"]').click();
    await page.getByRole('heading',{name:/STAFF UNFORGED|FAILED UNFORGING!/}).waitFor();
    await shot(page,'inventory-rust-unforge-result.png');
    await page.locator('[data-panel-action="notice-okay"]').click();
    await staff.waitFor({state:'detached'});
    await page.keyboard.press('KeyK'); await panel(page,'skills'); await page.waitForTimeout(450);
    assert.equal(await page.locator('[data-panel-action^="skill:"]').count(),2,'fresh book contains only learned skills');
    await shot(page,'skillbook-rust.png');
    const primary=page.locator('[data-panel-action="skill:8"]');
    await primary.hover(); await frames(page);
    await page.locator('.panel-tooltip-title').getByText('MAGIC MISSILE',{exact:false}).waitFor();
    await shot(page,'skillbook-rust-magic-missile.png');
    const secondary = await page.locator('[data-panel-action="skill:11"]').boundingBox();
    const belt = await page.locator('[data-panel-action="belt:2"]').boundingBox();
    await page.mouse.move(secondary.x+secondary.width/2,secondary.y+secondary.height/2);
    await page.mouse.down(); await frames(page);
    await page.mouse.move(belt.x+belt.width/2,belt.y+belt.height/2,{steps:12});
    await page.mouse.up(); await frames(page);
    assert.match(await page.locator('[data-panel-action="belt:2"]').getAttribute('aria-label'),/assign or drag away/,'skill binds through the live belt model');
    await page.keyboard.press('Escape');
    await page.locator('.player-panels').waitFor({state:'hidden'});
    assert.equal(await page.locator('.game-menus').getAttribute('data-menu-screen'),'hidden','panel Escape does not also open pause');
    await page.waitForFunction(tick => window.wasmBindings.wizard_state()[5] > tick,frozen[5]);
    assert.deepEqual(errors,[]);
    console.log(JSON.stringify({passed:true,errors,screenshots:output}));
  } finally { await browser.close(); }
})().catch(error=>{console.error(error);process.exitCode=1;});
