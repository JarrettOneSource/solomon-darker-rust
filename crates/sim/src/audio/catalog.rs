impl AudioCue {
    #[must_use]
    pub fn definition(self) -> &'static AudioDefinition {
        &AUDIO_CATALOG[self as usize]
    }
    #[must_use]
    pub fn from_id(id: &str) -> Option<Self> {
        AUDIO_CATALOG.iter().find(|definition| definition.id == id).map(|definition| definition.cue)
    }
    #[must_use]
    pub fn as_str(self) -> &'static str {
        self.definition().id
    }
    #[must_use]
    pub fn maximum_voices(self) -> Option<usize> {
        match self {
            Self::FireballHit
            | Self::ThrowFire
            | Self::Harden
            | Self::IceShatter
            | Self::HailBounce0
            | Self::HailBounce1
            | Self::HailBounce2
            | Self::HailBounce3 => Some(10),
            _ => None,
        }
    }
}
