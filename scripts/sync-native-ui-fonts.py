#!/usr/bin/env python3
"""Retain the pinned Website's exact stock bitmap-font tables as dependency-free Rust data."""
import json
import os
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
WEBSITE = Path(os.environ.get("SOLOMON_WEBSITE_DIR", ROOT.parent / "website-rust-current"))
SOURCE = WEBSITE / "frontend/src/assets/game/native-ui-assets.json"
TARGET = ROOT / "crates/sim/src/native_ui_text/catalog.rs"
FONT_NAMES = [
    ("belt", "Belt"),
    ("body", "Body"),
    ("control-panel", "ControlPanel"),
    ("heading", "Heading"),
    ("medium", "Medium"),
    ("menu", "Menu"),
    ("skill-uppercase", "SkillUppercase"),
    ("special-uppercase", "SpecialUppercase"),
    ("timeline", "Timeline"),
    ("world-and-roster", "WorldAndRoster"),
]


def array(values):
    return "[" + ", ".join(repr(float(value)) for value in values) + "]"


manifest = json.loads(SOURCE.read_text())
lines = [
    "//! Authored font records from Website `frontend/src/assets/game/native-ui-assets.json`.",
    "//! Generated by `scripts/sync-native-ui-fonts.py`; glyph and kerning order is sorted for lookup.",
    "",
    "use super::{NativeUiAtlasName, NativeUiBitmapFont, NativeUiGlyphRecord, NativeUiKerning};",
    "",
]
for name, variant in FONT_NAMES:
    font = manifest["fonts"][name]
    constant = name.upper().replace("-", "_")
    lines += ["#[rustfmt::skip]", f"const {constant}_GLYPHS: &[NativeUiGlyphRecord] = &["]
    for code, glyph in sorted(font["glyphs"].items(), key=lambda row: int(row[0])):
        assert not glyph["points"] and not glyph["rotated"]
        lines.append(
            f"    NativeUiGlyphRecord {{ code_point: {code}, record: {glyph['record']}, "
            f"frame: {array(glyph['frame'])}, logical_size: {array(glyph['logicalSize'])}, "
            f"trim_origin: {array(glyph['trimOrigin'])}, metrics: {array(glyph['metrics'])} }},"
        )
    lines += ["];", "", "#[rustfmt::skip]", f"const {constant}_KERNING: &[NativeUiKerning] = &["]
    for left, right, adjustment in sorted(font["kerning"]):
        lines.append(f"    NativeUiKerning {{ left: {left}, right: {right}, adjustment: {float(adjustment)!r} }},")
    lines += ["];", "", f"pub(super) const {constant}: NativeUiBitmapFont = NativeUiBitmapFont {{",
              f"    atlas: NativeUiAtlasName::{font['atlas']},",
              f"    metrics: {array(font['metrics'])},",
              f"    space_advance: {float(font['spaceAdvance'])!r},",
              f"    glyphs: {constant}_GLYPHS,", f"    kerning: {constant}_KERNING,", "};", ""]
TARGET.parent.mkdir(parents=True, exist_ok=True)
TARGET.write_text("\n".join(lines))
print(f"wrote {TARGET.relative_to(ROOT)}")
